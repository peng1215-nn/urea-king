/**
 * game_pdf.js — 三端统一牌局 PDF 导出
 * 依赖：jsPDF (loaded via CDN in each page that uses export)
 *
 * 主入口：
 *   generateGamePdf(game, groupName, lang)
 *     game      — 服务器返回的 game 对象（含 players 数组）
 *     groupName — 组名字符串（可从 current-user 或 admin select 获取）
 *     lang      — "zh" | "en"
 */

(function (global) {
    "use strict";

    // ── 双语字符串 ──────────────────────────────────────────────
    const I18N = {
        zh: {
            brand:        "UREAKING POKER",
            subtitle:     "牌局记录",
            group:        "组别",
            time:         "时间",
            duration:     "时长",
            totalBuyIn:   "总买入",
            balanced:     "已平衡",
            unbalanced:   "未平衡",
            players:      "玩家记录",
            rank:         "#",
            nickname:     "昵称",
            buyIn:        "买入",
            cashOut:      "卖出",
            net:          "盈亏",
            organizer:    "局头",
            topWinner:    "最大赢家",
            note:         "备注",
            exportedAt:   "导出时间",
            generatedBy:  "由 UREAKING POKER 生成",
            noPlayers:    "暂无玩家数据",
        },
        en: {
            brand:        "UREAKING POKER",
            subtitle:     "Game Record",
            group:        "Group",
            time:         "Time",
            duration:     "Duration",
            totalBuyIn:   "Total Buy-in",
            balanced:     "Balanced",
            unbalanced:   "Unbalanced",
            players:      "Players",
            rank:         "#",
            nickname:     "Nickname",
            buyIn:        "Buy-in",
            cashOut:      "Cash-out",
            net:          "Net",
            organizer:    "Organizer",
            topWinner:    "Top Winner",
            note:         "Note",
            exportedAt:   "Exported at",
            generatedBy:  "Generated by UREAKING POKER",
            noPlayers:    "No player data",
        },
    };

    // ── 颜色系统 ────────────────────────────────────────────────
    const C = {
        brand:       [92, 141, 255],   // 品牌蓝
        bg:          [255, 255, 255],  // 白底
        surface:     [248, 249, 252],  // 卡片背景（淡灰）
        headerBg:    [240, 244, 255],  // 表头背景（淡蓝）
        text:        [24, 28, 50],     // 主文字
        textMuted:   [110, 118, 145],  // 次要文字
        positive:    [34, 153, 102],   // 正收益绿
        negative:    [220, 60, 60],    // 负收益红
        zero:        [150, 155, 170],  // 零收益灰
        divider:     [220, 224, 235],  // 分割线
        badgeGreen:  [34, 153, 102],
        badgeRed:    [220, 60, 60],
        winnerBg:    [255, 248, 225],  // 最大赢家行背景
        winnerBorder:[255, 193, 7],
    };

    // ── 辅助函数 ────────────────────────────────────────────────
    function setFill(doc, rgb)   { doc.setFillColor(rgb[0], rgb[1], rgb[2]); }
    function setDraw(doc, rgb)   { doc.setDrawColor(rgb[0], rgb[1], rgb[2]); }
    function setTextColor(doc, rgb) { doc.setTextColor(rgb[0], rgb[1], rgb[2]); }

    function rect(doc, x, y, w, h, rgb) {
        setFill(doc, rgb);
        doc.rect(x, y, w, h, "F");
    }

    function line(doc, x1, y1, x2, y2, rgb, lw) {
        doc.setLineWidth(lw || 0.3);
        setDraw(doc, rgb);
        doc.line(x1, y1, x2, y2);
    }

    function text(doc, str, x, y, opts) {
        doc.text(String(str), x, y, opts || {});
    }

    function netColor(net) {
        if (net > 0) return C.positive;
        if (net < 0) return C.negative;
        return C.zero;
    }

    function netStr(net) {
        if (net > 0) return "+" + net;
        return String(net);
    }

    function nowString() {
        const d = new Date();
        const pad = n => String(n).padStart(2, "0");
        return d.getFullYear() + "-" + pad(d.getMonth() + 1) + "-" + pad(d.getDate()) +
               " " + pad(d.getHours()) + ":" + pad(d.getMinutes());
    }

    // ── PDF 生成主函数 ───────────────────────────────────────────
    function generateGamePdf(game, groupName, lang) {
        if (!window.jspdf || !window.jspdf.jsPDF) {
            console.error("jsPDF not loaded");
            return;
        }
        const { jsPDF } = window.jspdf;
        const s = I18N[lang] || I18N.zh;

        const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
        const PW = 210;   // page width
        const PH = 297;   // page height
        const ML = 16;    // margin left
        const MR = 16;    // margin right
        const CW = PW - ML - MR;  // content width

        // ── 白底 ────────────────────────────────────────────────
        rect(doc, 0, 0, PW, PH, C.bg);

        let y = 0;

        // ── Header bar (品牌蓝) ─────────────────────────────────
        const HEADER_H = 22;
        rect(doc, 0, 0, PW, HEADER_H, C.brand);

        // 品牌名
        doc.setFont("helvetica", "bold");
        doc.setFontSize(13);
        setTextColor(doc, [255, 255, 255]);
        text(doc, s.brand, ML, 10);

        // 副标题（右对齐）
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        setTextColor(doc, [200, 215, 255]);
        text(doc, s.subtitle, PW - MR, 10, { align: "right" });

        y = HEADER_H + 10;

        // ── 牌局名称 ────────────────────────────────────────────
        const gameName = game.name || ("Game #" + game.id);
        doc.setFont("helvetica", "bold");
        doc.setFontSize(18);
        setTextColor(doc, C.text);
        text(doc, gameName, ML, y);
        y += 7;

        // ── 元信息行（组别 · 时间 · 时长）───────────────────────
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        setTextColor(doc, C.textMuted);

        const metaParts = [];
        if (groupName) metaParts.push(s.group + ": " + groupName);
        if (game.started_at && game.ended_at) {
            metaParts.push(s.time + ": " + game.started_at + " → " + game.ended_at);
        }
        if (game.duration) metaParts.push(s.duration + ": " + game.duration);
        text(doc, metaParts.join("   ·   "), ML, y);
        y += 5;

        // ── 总买入 + 平衡徽章 ───────────────────────────────────
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        setTextColor(doc, C.textMuted);
        text(doc, s.totalBuyIn + ": " + (game.total_buy_in || 0), ML, y);

        // 平衡状态徽章
        const badgeText = game.is_balanced ? s.balanced : s.unbalanced;
        const badgeColor = game.is_balanced ? C.badgeGreen : C.badgeRed;
        const badgeX = ML + 45;
        const badgeW = 20;
        const badgeH = 5;
        rect(doc, badgeX, y - 4, badgeW, badgeH, badgeColor.map(v => Math.round(v * 0.15 + 255 * 0.85)));
        doc.setFont("helvetica", "bold");
        doc.setFontSize(7.5);
        setTextColor(doc, badgeColor);
        text(doc, badgeText, badgeX + badgeW / 2, y - 0.5, { align: "center" });

        y += 8;

        // ── 分割线 ──────────────────────────────────────────────
        line(doc, ML, y, PW - MR, y, C.divider, 0.4);
        y += 6;

        // ── Section: 玩家记录 ───────────────────────────────────
        doc.setFont("helvetica", "bold");
        doc.setFontSize(10);
        setTextColor(doc, C.brand);
        text(doc, s.players, ML, y);
        y += 5;

        // ── 表格 ────────────────────────────────────────────────
        const players = game.players || [];

        // 列宽分配
        const COL = {
            rank:     12,
            nickname: 62,
            buyIn:    30,
            cashOut:  30,
            net:      CW - 12 - 62 - 30 - 30,  // 剩余
        };
        const COL_X = {
            rank:     ML,
            nickname: ML + COL.rank,
            buyIn:    ML + COL.rank + COL.nickname,
            cashOut:  ML + COL.rank + COL.nickname + COL.buyIn,
            net:      ML + COL.rank + COL.nickname + COL.buyIn + COL.cashOut,
        };

        const ROW_H = 9;
        const HEADER_ROW_H = 8;

        // 表头背景
        rect(doc, ML, y, CW, HEADER_ROW_H, C.headerBg);

        // 表头文字
        doc.setFont("helvetica", "bold");
        doc.setFontSize(8);
        setTextColor(doc, C.textMuted);

        const headers = [
            { key: "rank",     label: s.rank,     align: "center" },
            { key: "nickname", label: s.nickname,  align: "left" },
            { key: "buyIn",    label: s.buyIn,     align: "right" },
            { key: "cashOut",  label: s.cashOut,   align: "right" },
            { key: "net",      label: s.net,       align: "right" },
        ];

        headers.forEach(h => {
            const cx = h.align === "center" ? COL_X[h.key] + COL[h.key] / 2
                     : h.align === "right"  ? COL_X[h.key] + COL[h.key] - 2
                     : COL_X[h.key] + 2;
            text(doc, h.label, cx, y + HEADER_ROW_H - 2.5, { align: h.align });
        });

        y += HEADER_ROW_H;

        // 表格行
        if (players.length === 0) {
            doc.setFont("helvetica", "normal");
            doc.setFontSize(9);
            setTextColor(doc, C.textMuted);
            text(doc, s.noPlayers, ML + CW / 2, y + ROW_H - 2.5, { align: "center" });
            y += ROW_H;
        } else {
            players.forEach((p, i) => {
                // 检查分页（留出 footer 空间 30mm）
                if (y + ROW_H > PH - 30) {
                    doc.addPage();
                    rect(doc, 0, 0, PW, PH, C.bg);
                    y = 16;
                }

                const isWinner = p.user_id === game.top_winner_id;
                const rowBg = isWinner ? C.winnerBg
                            : i % 2 === 0 ? C.bg : C.surface;
                rect(doc, ML, y, CW, ROW_H, rowBg);

                // 最大赢家左侧色条
                if (isWinner) {
                    rect(doc, ML, y, 2.5, ROW_H, C.winnerBorder);
                }

                const midY = y + ROW_H - 2.8;

                // 排名
                doc.setFont("helvetica", "normal");
                doc.setFontSize(8);
                setTextColor(doc, C.textMuted);
                text(doc, String(i + 1), COL_X.rank + COL.rank / 2, midY, { align: "center" });

                // 昵称 + 标签
                doc.setFont("helvetica", isWinner ? "bold" : "normal");
                doc.setFontSize(8.5);
                setTextColor(doc, C.text);
                let nameStr = p.nickname || "-";

                // 追加标签文字
                const tags = [];
                if (p.is_organizer) tags.push("[" + s.organizer + "]");
                if (isWinner)       tags.push("★ " + s.topWinner);
                const tagStr = tags.length ? "  " + tags.join(" ") : "";

                const maxNickW = COL.nickname - 4;
                // 截断过长昵称（jsPDF 没有内置 ellipsis，手动估算）
                const charW = 2.1; // 约 8.5pt @ mm 估算
                while (doc.getTextWidth(nameStr + tagStr) > maxNickW && nameStr.length > 1) {
                    nameStr = nameStr.slice(0, -1);
                }

                doc.setFont("helvetica", isWinner ? "bold" : "normal");
                setTextColor(doc, C.text);
                text(doc, nameStr, COL_X.nickname + 2, midY);

                if (tags.length) {
                    const tagX = COL_X.nickname + 2 + doc.getTextWidth(nameStr) + 1;
                    doc.setFont("helvetica", "normal");
                    doc.setFontSize(7);
                    setTextColor(doc, isWinner ? C.winnerBorder : C.textMuted);
                    text(doc, tags.join(" "), tagX, midY);
                }

                // 买入
                doc.setFont("helvetica", "normal");
                doc.setFontSize(8.5);
                setTextColor(doc, C.text);
                text(doc, String(p.total_buy_in || 0), COL_X.buyIn + COL.buyIn - 2, midY, { align: "right" });

                // 卖出
                text(doc, String(p.cash_out || 0), COL_X.cashOut + COL.cashOut - 2, midY, { align: "right" });

                // 盈亏（颜色）
                doc.setFont("helvetica", "bold");
                setTextColor(doc, netColor(p.net));
                text(doc, netStr(p.net), COL_X.net + COL.net - 2, midY, { align: "right" });

                // 行底线
                line(doc, ML, y + ROW_H, ML + CW, y + ROW_H, C.divider, 0.2);

                y += ROW_H;
            });
        }

        y += 6;

        // ── 备注（如有）────────────────────────────────────────
        if (game.note) {
            if (y + 14 > PH - 30) {
                doc.addPage();
                rect(doc, 0, 0, PW, PH, C.bg);
                y = 16;
            }
            line(doc, ML, y, ML + CW, y, C.divider, 0.3);
            y += 5;
            doc.setFont("helvetica", "bold");
            doc.setFontSize(8.5);
            setTextColor(doc, C.textMuted);
            text(doc, s.note + ":", ML, y);
            y += 5;
            doc.setFont("helvetica", "normal");
            doc.setFontSize(8.5);
            setTextColor(doc, C.text);

            // 自动换行
            const noteLines = doc.splitTextToSize(game.note, CW - 4);
            noteLines.forEach(l => {
                if (y + 5 > PH - 30) {
                    doc.addPage();
                    rect(doc, 0, 0, PW, PH, C.bg);
                    y = 16;
                }
                text(doc, l, ML + 2, y);
                y += 5;
            });
            y += 4;
        }

        // ── Footer ─────────────────────────────────────────────
        const totalPages = doc.getNumberOfPages();
        for (let pg = 1; pg <= totalPages; pg++) {
            doc.setPage(pg);
            const fy = PH - 10;
            line(doc, ML, fy - 4, PW - MR, fy - 4, C.divider, 0.3);
            doc.setFont("helvetica", "normal");
            doc.setFontSize(7.5);
            setTextColor(doc, C.textMuted);
            text(doc, s.exportedAt + ": " + nowString(), ML, fy);
            text(doc, s.generatedBy, PW - MR, fy, { align: "right" });
            if (totalPages > 1) {
                text(doc, pg + " / " + totalPages, PW / 2, fy, { align: "center" });
            }
        }

        // ── 保存文件 ────────────────────────────────────────────
        const filename = (game.name || ("game_" + game.id)).replace(/[/\\?%*:|"<>]/g, "_") + ".pdf";
        doc.save(filename);
    }

    global.generateGamePdf = generateGamePdf;

})(window);
